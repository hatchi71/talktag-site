import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const library = fs.readFileSync('audio-library.html', 'utf8');
const player = fs.readFileSync('audio-player.html', 'utf8');
const playerCode = fs.readFileSync('audio-player.js', 'utf8');
const englishLanding = fs.readFileSync('E-english.html', 'utf8');
const japaneseLanding = fs.readFileSync('japanese/J-index.html', 'utf8');
const koreanLanding = fs.readFileSync('K-korean-learning.html', 'utf8');
const koreanLibrary = fs.readFileSync('K-korean-audio-library.html', 'utf8');
const japaneseLibrary = fs.readFileSync('japanese/J-guided.html', 'utf8');
const englishLibraryCode = fs.readFileSync('audio-library.js', 'utf8');
const nativeLibraryCode = fs.readFileSync('native-audio-library.js', 'utf8');
const news = JSON.parse(fs.readFileSync('home-news-feed.json', 'utf8'));
const source = fs.readFileSync('mini-talks-001.js', 'utf8');
const context = { window: {} };
vm.createContext(context);
vm.runInContext(source, context);
const lessons = context.window.TalkTagAudioLessons;
assert.deepEqual(Array.from(lessons, lesson => lesson.level), ['A1', 'A2', 'B1', 'B2', 'C1', 'C2']);
assert.equal(new Set(lessons.map(lesson => lesson.id)).size, 6);
for (const lesson of lessons) {
  assert.equal(lesson.type, 'plain');
  assert.equal(lesson.format, 'mini-talks');
  assert.match(lesson.audio, /^https:\/\/audio\.talktag\.co\.kr\/English\/mini-talks\/001\//);
  assert.equal(lesson.expressions.length, lesson.meanings.length);
  assert.equal(lesson.expressions.length, lesson.speakers.length);
  assert.equal(lesson.training.playthroughs, 1);
  assert.equal(lesson.training.cues.length, lesson.expressions.length);
  assert.equal(lesson.training.defaultReps, undefined);
  assert.equal(lesson.training.variationPromptAt, undefined);
  assert.equal(lesson.training.outro, undefined);
  assert.ok(lesson.training.cues.at(-1).e < lesson.training.endingCueStart);
  assert.ok(fs.existsSync(lesson.artwork), `${lesson.id}: missing artwork`);
  assert.ok(lesson.artworkAlt);
}
assert.equal(new Set(lessons.map(lesson => lesson.artwork)).size, 6);
assert.match(library, /src="mini-talks-001\.js/);
assert.match(library, /02 · JOT DOWN/);
assert.match(library, /03 · SUMMARIZE AND RETELL/);
assert.doesNotMatch(library, /02 · REPEAT/);
assert.doesNotMatch(library, /src="audio-essays(?:-002(?:-media)?)?\.js/);
assert.match(player, /src="mini-talks-001\.js/);
assert.doesNotMatch(playerCode, /miniTalksPrompt/, 'Removed Mini Talks prompt must not stop player initialization');
assert.match(playerCode, /playButton\.addEventListener\("click"/, 'Mini Talks player must retain the play handler');
assert.match(player, /src="audio-essays\.js/);
assert.match(englishLanding, /<strong>미니토크<\/strong>/);
assert.match(japaneseLanding, /<strong>미니토크<\/strong>/);
assert.match(koreanLanding, /<strong>Mini Talks /);
assert.match(koreanLibrary, />Mini Talks<\/a>/);
assert.match(japaneseLibrary, />미니토크<\/a>/);
assert.match(library, /미니토크 · 이렇게 연습하세요/);
assert.match(englishLibraryCode, /"미니토크"/);
assert.match(nativeLibraryCode, /japanese\?\(type==="guided"\?"듣고 따라 말하기":"미니토크"\):\(type==="guided"\?"Guided Listen & Repeat":"Mini Talks"\)/);
assert.match(playerCode, / · 미니토크/);
assert.equal(news.items.find(item => item.id === 'mini:en:001')?.title, '영어 미니토크 · 001');
assert.equal(news.items.find(item => item.id === 'mini:en:001')?.levels.length, 6);
assert.ok(!news.items.some(item => item.id === 'plain:001' || item.id === 'plain:002'));
console.log('Mini Talks catalog: six replacement cards, archive deep links, home news, and cue timing PASS');
